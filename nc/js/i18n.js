const LANGS = ['pt', 'en', 'es'];
const LANG_LABELS = { pt: '🇧🇷 PT', en: '🇺🇸 EN', es: '🇪🇸 ES' };

const I18N = {
  get lang() {
    const l = Store.state && Store.state.lang;
    return LANGS.indexOf(l) >= 0 ? l : 'pt';
  },
  set(lang) {
    Store.state.lang = LANGS.indexOf(lang) >= 0 ? lang : 'pt';
    Store.save();
  },
  // next language in the PT → EN → ES cycle of the header button
  nextLang() { return LANGS[(LANGS.indexOf(this.lang) + 1) % LANGS.length]; },
  label() { return LANG_LABELS[this.lang]; },
  // t('key') or t('key', {n: 3}) — {placeholders} get replaced
  t(key, vars) {
    const d = STRINGS[this.lang] || STRINGS.pt;
    let s = d[key] !== undefined ? d[key] : STRINGS.en[key];
    if (s === undefined) return key;
    if (Array.isArray(s)) return s;
    if (vars) Object.keys(vars).forEach(k => { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
  },
  // localized field of a data object: pick(obj, 'question') → question_pt / question_es / question (EN fallback)
  pick(o, field) {
    if (this.lang !== 'en') {
      const v = o[field + '_' + this.lang];
      if (v && (!Array.isArray(v) || v.length === 4)) return v;
    }
    return o[field];
  },
  // question fields honoring the active language (EN fallback) — R11.3
  qText(q) { return this.pick(q, 'question'); },
  qChoices(q) { return this.pick(q, 'choices'); },
  qExpl(q) { return this.pick(q, 'explanation'); },
  signName(m) { return this.pick(m, 'name'); },
  signMeaning(m) { return this.pick(m, 'meaning'); },
  topicName(t) { return this.pick(t, 'name'); },
  diff(d) { return this.t('diff_' + d); }
};
